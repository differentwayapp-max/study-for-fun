def CARD(*lines, e=None):
    """Hebrew text on cards, one line under the other; an emoji in the corner."""
    n = len(lines); s = round(min(15, 160 / max(len(l) for l in lines), 12.5 if n >= 4 else 15), 1)
    ys = {1: [50], 2: [36, 64], 3: [24, 50, 76], 4: [17, 38, 59, 80]}[n]
    return ([(e, 8, 13, 16)] if e else []) + [(l, 52 if e else 50, y, s) for l, y in zip(lines, ys)]
def _w(n, s): return (n * .6 + .8) * s / 1.6
def TAB(*rows):
    """A small table, Hebrew-style: the row name on the right, the values to its left."""
    n, k = len(rows), len(rows[0]) - 1; ys = {1: [45], 2: [30, 58], 3: [20, 43, 66]}[n]
    hl, vl = max(len(r[0]) for r in rows), max(len(v) for r in rows for v in r[1:])
    for s in range(15, 9, -1):
        hw, vw = _w(hl, s), _w(vl, s); step = vw + 2.5; total = hw + 3 + step * (k - 1) + vw
        if total <= 95: break
    right = 50 + total / 2; hx = right - hw / 2; x0 = right - hw - 3 - vw / 2
    out = []
    for r, y in zip(rows, ys):
        out.append((r[0], round(hx, 1), y, s))
        out += [(v, round(x0 - i * step, 1), y, s) for i, v in enumerate(r[1:])]
    return out
def BARS(*rows):
    """A bar chart lying on its side: the label (an emoji) on the right, a bar of ■ growing to the left."""
    n = len(rows); z = 13; out = []
    for i, (lab, k) in enumerate(rows):
        y = round(14 + 72 * (i + .5) / n, 1); bar = "■" * k; hw = z * .48 * len(bar) / 1.6 + 2   # real width of ■ in the app font
        out += [(lab, 89, y, 18), (bar, round(79 - hw, 1), y, z)]
    return out
def AREA(a, b):
    """Two shapes made of unit squares: shape א' on the right, ב' on the left, the names under them."""
    out = []
    for rows, x, name in ((a, 72, "א'"), (b, 28, "ב'")):
        n = len(rows); z = min(13, 56 / n)
        out += [(r, x, round(12 + 64 * (i + .5) / n, 1), round(z)) for i, r in enumerate(rows)] + [(name, x, 88, 12)]
    return out
