# ---- helpers -------------------------------------------------------------------------------------------------
HEB = re.compile(r"[֐-׿]")
def W(s):
    """{…} → left-to-right inside Hebrew text (numbers, math)."""
    return re.sub(r"\{([^}]*)\}", lambda m: "⁦" + m.group(1) + "⁩", s)

def O(o):
    o = W(o)
    return o if HEB.search(o) or o.startswith("⁦") else "⁦" + o + "⁩"

def Q(topic, q, opts, expl, sc):
    """The right answer is always written first; the builder shuffles the options."""
    return (topic, W(q), [O(o) for o in opts], 0, W(expl), sc)

def ROW(*es):
    """A few different emoji in a row (the things the question talks about). The first one is on the LEFT."""
    n = len(es); s = min(40, 112 / n); step = min(92 / n, s * 1.05)
    return [(e, round(50 + (j - (n - 1) / 2) * step, 1), 50, round(s)) for j, e in enumerate(es)]

def CARD(*lines, e=None):
    """Hebrew text on a card, one line under the other (≤16 characters a line); an emoji in the corner."""
    n = len(lines); s = round(min(15, 160 / max(len(l) for l in lines), 12.5 if n >= 4 else 15), 1)
    ys = {1: [50], 2: [36, 64], 3: [24, 50, 76], 4: [17, 38, 59, 80]}[n]
    return ([(e, 8, 13, 16)] if e else []) + [(l, 52 if e else 50, y, s) for l, y in zip(lines, ys)]

def S(text, e=None):
    """A sentence on a card, wrapped into lines of ≤16 characters."""
    lines, cur = [], ""
    for w in text.split():
        if cur and len(cur) + 1 + len(w) > 16: lines.append(cur); cur = w
        else: cur = (cur + " " + w).strip()
    lines.append(cur)
    assert len(lines) <= 4, text
    return CARD(*lines, e=e)

def WC(word, e):
    """A word on a card under the thing it is about."""
    return [(e, 50, 30, 36), (word, 50, 76, min(20, round(140 / max(len(word), 1))))]

def _w(n, s):
    """Real width of a text card with n characters at size s, in % of the frame width (the frame is 16:10)."""
    return (n * .6 + .8) * s / 1.6

def TAB(*rows):
    """A small table, Hebrew-style: the row name on the right, the values to its left (first value next to the name)."""
    n, k = len(rows), len(rows[0]) - 1; ys = {1: [45], 2: [30, 58], 3: [20, 43, 66]}[n]
    hl, vl = max(len(r[0]) for r in rows), max(len(v) for r in rows for v in r[1:])
    for s in range(15, 9, -1):
        hw, vw = _w(hl, s), _w(vl, s); step = vw + 2.5; total = hw + 3 + step * (k - 1) + vw
        if total <= 95: break
    right = 50 + total / 2; hx = right - hw / 2; x0 = right - hw - 3 - vw / 2
    out = []
    for r, y in zip(rows, ys):
        out.append((r[0], round(hx, 1), y, s))
        out += [(v, round(x0 - i * step, 1), y, s) for i, v in enumerate(r[1:])]
    return out

def GRAPH(xname, yname, xs, ys, lo=None, hi=None):
    """A dot graph: red points (height = value), the x values under them, the axis names (y top-left, x bottom-right)."""
    lo = min(ys) if lo is None else lo; hi = max(ys) if hi is None else hi; k = len(xs)
    nw = _w(len(xname), 11); nx = 98.5 - nw / 2; right = min(76, nx - nw / 2 - 7 - _w(max(len(str(v)) for v in xs), 10) / 2)
    px = [13 + i * (right - 13) / (k - 1) for i in range(k)]
    py = [48 if hi == lo else 74 - (y - lo) / (hi - lo) * 50 for y in ys]
    out = [("🔴", round(x, 1), round(y, 1), 10) for x, y in zip(px, py)]
    out += [(str(v), round(x, 1), 90, 10) for v, x in zip(xs, px)]
    return out + [(yname, round(2 + _w(len(yname), 11) / 2, 1), 11, 11), (xname, round(nx, 1), 90, 11)]

def ROOTQ(word, root, wrong, e, expl):
    return Q(ROOT, f'מה השורש של המילה "{word}"?', [root] + wrong, expl, WC(word, e))

def BNQ(word, bn, wrong, e, expl):
    return Q(BIN, f'באיזה בניין המילה "{word}"?', [bn] + wrong, expl, WC(word, e))

