HEB = re.compile(r"[֐-׿]")
def W(s):
    s = re.sub(r"\{([^}]*)\}", lambda m: "⁦" + m.group(1) + "⁩", s)
    return s
def O(o):
    o = W(o)
    return o if HEB.search(o) or o.startswith("⁦") else "⁦" + o + "⁩"

def Q(topic, q, opts, ans, expl, sc, lvl=1):
    t = (topic, W(q), [O(o) for o in opts], ans, W(expl), sc)
    return t + (2,) if lvl == 2 else t
def Q2(*a): return Q(*a, lvl=2)        # a test-level question (the level of a real grade-7 test)


_TXT = TXT
def TXT(*lines, **k):
    """A long "… = ?" goes on two lines, so the numbers are drawn bigger."""
    if len(lines) == 1 and len(lines[0]) > 9 and lines[0].endswith(" = ?"): lines = (lines[0][:-4], "= ?")
    return _TXT(*lines, **k)

def PT(e, *lines):
    """A picture above, the given numbers below it (a card, left-to-right)."""
    if len(lines) == 1 and len(lines[0]) > 10 and " = " in lines[0]:      # a long equation: two bigger lines
        a, b = lines[0].split(" = ", 1); lines = (a, "= " + b)
    n = len(lines); z = min(20, 15 if n > 1 else 20, 140 / max(len(l) for l in lines))
    if n == 1: return [(e, 50, 30, 38), (lines[0], 50, 76, round(z))]
    return [(e, 50, 24, 32)] + [(l, 50, round(50 + 42 * (i + .5) / n, 1), round(z)) for i, l in enumerate(lines)]

def MOVE(start, arrow, steps):
    """A number (or point) on top, and the move under it: ➡️ 3."""
    return [(start, 50, 32, 26), (arrow, 38, 74, 24), (steps, 62, 74, 24)]

def NEG(a):
    """The opposite of a: "a 🔁 ?"."""
    return [(a, 78, 52, 26), ("🔁", 50, 52, 30), ("?", 22, 52, 26)]   # read right to left, like the question

