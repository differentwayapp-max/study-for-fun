def W(s): return re.sub(r"\{([^}]*)\}", lambda m: "⁦" + m.group(1) + "⁩", s)
def O(o): o = W(o); return o if re.search(r"[֐-׿]", o) or o.startswith("⁦") else "⁦" + o + "⁩"
def Q(topic, q, opts, ans, expl, sc): return (topic, W(q), [O(o) for o in opts], ans, W(expl), sc)

