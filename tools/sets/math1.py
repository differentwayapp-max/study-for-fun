def PAIRS(e, k, extra=0):                                               # k pairs side by side (2 pairs a row), plus single ones
    groups = [2] * k + ([extra] if extra else []); rows = [groups[i:i + 2] for i in range(0, len(groups), 2)]
    s = min(30, 0.75 * 74 / len(rows), 90 * 1.6 / (4 * 1.3 + 1.2)); w, g, out = s / 1.6 * 1.3, s / 1.6 * 1.2, []
    for r, row in enumerate(rows):
        xs, x = [], 0
        for gi, n in enumerate(row):
            for j in range(n): xs.append(x); x += w
            x += g - w if gi < len(row) - 1 else 0
        x0 = 50 - (xs[-1] - xs[0]) / 2 - xs[0]; y = 10 + 74 * (r + .5) / len(rows)
        out += [(e, round(x0 + xi, 1), round(y, 1), round(s)) for xi in xs]
    return out
