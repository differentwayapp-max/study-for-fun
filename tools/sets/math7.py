def _tight(l):
    """A long math line without Hebrew loses its spaces, so it is drawn bigger."""
    return l if len(l) <= 9 or HEB.search(l) or "," in l else l.replace(" ", "")

_TXT0 = TXT
def _TXT(*lines, **k): return _TXT0(*[_tight(l) for l in lines], **k)
def TXT(*lines, **k):
    """A long "… = ?" goes on two lines, so the numbers are drawn bigger."""
    if len(lines) == 1 and len(lines[0]) > 9 and lines[0].endswith(" = ?"): lines = (lines[0][:-4], "= ?")
    return _TXT(*lines, **k)

def EQ(eq, ask="x = ?"):
    """An equation card and what to find."""
    return _TXT(eq, ask)

def PT(e, *lines):
    """A picture above, the given numbers below it (a card)."""
    lines = [_tight(l) for l in lines]
    n = len(lines); z = min(20, 15 if n > 1 else 20, 140 / max(len(l) for l in lines))
    if n == 1: return [(e, 50, 30, 38), (lines[0], 50, 76, round(z))]
    return [(e, 50, 24, 32)] + [(l, 50, round(50 + 42 * (i + .5) / n, 1), round(z)) for i, l in enumerate(lines)]

def ROW(*es):
    n = len(es); s = min(40, 112 / n); step = min(92 / n, s * 1.05)
    return [(e, round(50 + (j - (n - 1) / 2) * step, 1), 50, round(s)) for j, e in enumerate(es)]

def _w(n, s):
    return (n * .6 + .8) * s / 1.6

def TAB(*rows):
    """A small table, Hebrew-style: the row name on the right, the values to its left."""
    n, k = len(rows), len(rows[0]) - 1; ys = {1: [45], 2: [30, 58], 3: [20, 43, 66]}[n]
    hl, vl = max(len(r[0]) for r in rows), max(len(v) for r in rows for v in r[1:])
    for s in range(15, 9, -1):
        hw, vw = _w(hl, s), _w(vl, s); step = vw + 2.5; total = hw + 3 + step * (k - 1) + vw
        if total <= 95: break
    right = 50 + total / 2; hx = right - hw / 2; x0 = right - hw - 3 - vw / 2
    out = []
    for r, y in zip(rows, ys):
        out.append((r[0], round(hx, 1), y, s))
        out += [(v, round(x0 - i * step, 1), y, s) for i, v in enumerate(r[1:])]
    return out

def LTAB(*rows):
    """A math table x / y read left to right (x values grow to the right, like on the axis)."""
    n, k = len(rows), len(rows[0]); ys = {1: [45], 2: [32, 62]}[n]
    vl = max(len(v) for r in rows for v in r)
    s = 15; step = max(_w(vl, s) + 4, 14); total = step * k
    x0 = 50 - total / 2 + step / 2
    out = []
    for r, y in zip(rows, ys):
        out += [(v, round(x0 + i * step, 1), y, s) for i, v in enumerate(r)]
    return out

def GRAPH(xname, yname, xs, ys, lo=None, hi=None):
    """A dot graph: red points (height = value), the x values under them, the axis names."""
    lo = min(ys) if lo is None else lo; hi = max(ys) if hi is None else hi; k = len(xs)
    nw = _w(len(xname), 11); nx = 98.5 - nw / 2; right = min(76, nx - nw / 2 - 7 - _w(max(len(str(v)) for v in xs), 10) / 2)
    px = [13 + i * (right - 13) / (k - 1) for i in range(k)]
    py = [48 if hi == lo else 74 - (y - lo) / (hi - lo) * 50 for y in ys]
    out = [("🔴", round(x, 1), round(y, 1), 10) for x, y in zip(px, py)]
    out += [(str(v), round(x, 1), 90, 10) for v, x in zip(xs, px)]
    return out + [(yname, round(2 + _w(len(yname), 11) / 2, 1), 11, 11), (xname, round(nx, 1), 90, 11)]

def GRAPHV(xs, ys, ticks):
    """A dot graph you can read values from: red points, the x values under them,
    and the values on the left at the height of each tick (the points sit on tick heights)."""
    lo, hi, k = min(ticks), max(ticks), len(xs)
    tw = _w(max(len(str(t)) for t in ticks), 10); tx = round(2 + tw / 2, 1)
    left = tx + tw / 2 + 10; right = 90
    px = [left + i * (right - left) / (k - 1) for i in range(k)]
    h = lambda v: round(74 - (v - lo) / (hi - lo) * 54, 1)
    out = [("🔴", round(x, 1), h(y), 9) for x, y in zip(px, ys)]
    out += [(str(v), round(x, 1), 91, 10) for v, x in zip(xs, px)]
    return out + [(str(t), tx, h(t), 10) for t in ticks]

def PAR(*lines):
    """Two parallel lines cut by a transversal – the given angle as a card."""
    return _TXT("a ∥ b", *lines)

